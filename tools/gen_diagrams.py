"""
Draw the diagrams in docs/img/ for the OEROS guide.

Dark, because the documentation site is dark. The brand fonts are embedded as
small subsets, so the SVGs look the same in a browser, on GitHub and on the
site without the fonts installed. The fonts are under the SIL Open Font
License 1.1, which allows embedding them in documents.

    python tools/gen_diagrams.py --fonts DIR    # DIR holds WorkSans-*.ttf, RobotoMono-Regular.ttf
"""

import argparse
import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

OUT = Path(__file__).resolve().parent.parent / 'docs' / 'img'

BG, BLOCK, LINE = '#1A1A1A', '#242424', '#E4E5D4'
WHITE, CREAM, PINK, MUTED = '#FFFFFF', '#ECEDDF', '#F286DA', '#8A93A0'
CHARS = ''.join(chr(c) for c in range(32, 127)) + '·×’→…'
FONTS = {('Work Sans', 400): 'WorkSans-Regular.ttf', ('Work Sans', 500): 'WorkSans-Medium.ttf',
         ('Roboto Mono', 400): 'RobotoMono-Regular.ttf'}


def font_faces(fonts_dir):
    faces = []
    for (family, weight), name in FONTS.items():
        font = TTFont(str(Path(fonts_dir) / name))
        sub = subset.Subsetter()
        sub.populate(text=CHARS)
        sub.subset(font)
        buf = io.BytesIO()
        font.save(buf)
        data = base64.b64encode(buf.getvalue()).decode()
        faces.append(f"@font-face{{font-family:'{family}';font-weight:{weight};"
                     f"src:url(data:font/ttf;base64,{data}) format('truetype')}}")
    return ''.join(faces)


class Svg:
    def __init__(self, w, h, label, faces):
        self.w, self.h, self.items = w, h, []
        self.head = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" '
                     f'height="{h}" role="img" aria-label="{label}">'
                     '<!-- SPDX-FileCopyrightText: 2026 SMAROBIX GmbH -->'
                     '<!-- SPDX-License-Identifier: Apache-2.0. Embedded font subsets: Work Sans, '
                     'Roboto Mono, SIL Open Font License 1.1. Generated by tools/gen_diagrams.py. -->'
                     f'<style>{faces}text{{font-family:"Work Sans",Helvetica,Arial,sans-serif}}'
                     '.m{font-family:"Roboto Mono",Menlo,monospace}</style>'
                     f'<rect width="{w}" height="{h}" fill="{BG}"/>')

    def rect(self, x, y, w, h, fill=BLOCK, stroke=LINE, dash=False):
        d = ' stroke-dasharray="5 4"' if dash else ''
        s = f' stroke="{stroke}" stroke-width="1"{d}' if stroke else ''
        self.items.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}"{s}/>')

    def text(self, x, y, t, size=13, color=CREAM, weight=400, mono=False, anchor='start', track=0):
        cls = ' class="m"' if mono else ''
        sp = f' letter-spacing="{track}"' if track else ''
        t = t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        self.items.append(f'<text{cls} x="{x}" y="{y}" font-size="{size}" font-weight="{weight}" '
                          f'fill="{color}" text-anchor="{anchor}"{sp}>{t}</text>')

    def tag(self, x, y, t, color=MUTED):
        self.text(x, y, t.upper(), size=10.5, color=color, weight=500, track=1)

    def arrow(self, points, color=CREAM, dash=False, head=True):
        d = ' stroke-dasharray="5 4"' if dash else ''
        pts = ' '.join(f'{x},{y}' for x, y in points)
        self.items.append(f'<polyline points="{pts}" fill="none" stroke="{color}" stroke-width="1.5"{d}/>')
        if head:
            (x1, y1), (x2, y2) = points[-2], points[-1]
            if x1 == x2:
                s = 1 if y2 > y1 else -1
                tri = [(x2, y2), (x2 - 5, y2 - 9 * s), (x2 + 5, y2 - 9 * s)]
            else:
                s = 1 if x2 > x1 else -1
                tri = [(x2, y2), (x2 - 9 * s, y2 - 5), (x2 - 9 * s, y2 + 5)]
            p = 'M' + ' L'.join(f'{a},{b}' for a, b in tri) + ' Z'
            self.items.append(f'<path d="{p}" fill="{color}"/>')

    def write(self, name):
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / name).write_text(self.head + ''.join(self.items) + '</svg>\n')


def pick_image(faces):
    s = Svg(960, 320, 'Which image to build with: on an x86_64 computer, oeros-sdk-cross; on an arm64 '
            'computer, oeros-sdk-target. Both build for the same arm64 OEROS robot.', faces)
    s.tag(24, 32, 'Your computer')
    s.tag(330, 32, 'docker_image in .buildx.conf')
    s.tag(760, 32, 'Your robot')
    rows = [('x86_64 computer', 'Linux, Windows, an Intel Mac', 'oeros-sdk-cross:<distro>-arm64',
             'Cross SDK · runs on x86_64'),
            ('arm64 computer', 'Apple silicon, arm64 Linux', 'oeros-sdk-target:<distro>-arm64',
             'On-target SDK · runs on arm64')]
    for i, (comp, sub, image, kind) in enumerate(rows):
        y = 50 + i * 120
        s.rect(24, y, 250, 90)
        s.text(40, y + 38, comp, size=16, color=WHITE, weight=500)
        s.text(40, y + 62, sub)
        s.arrow([(274, y + 45), (330, y + 45)])
        s.rect(330, y, 370, 90)
        s.text(346, y + 40, image, size=14, color=WHITE, mono=True)
        s.tag(346, y + 66, kind, color=PINK)
        s.arrow([(700, y + 45), (730, y + 45), (730, 155), (760, 155)], head=(i == 1))
    s.rect(760, 50, 176, 210)
    s.text(776, 88, 'OEROS robot', size=16, color=WHITE, weight=500)
    for k, line in enumerate(('arm64, running an', 'image from the OEROS', 'stack, such as', 'oeros-ros-base')):
        s.text(776, 114 + k * 20, line, mono=(k == 3))
    s.text(24, 296, 'Both build the same workspace for the same robot. An image that would need emulation is '
           'refused, and colcon buildx names the one to use.', color=MUTED, size=12.5)
    s.write('oeros-pick-image.svg')


