"""CMake toolchain wrapper shared by the SDK-based backends.

An OE/Yocto SDK ships a stock CMake toolchain file that is fine for building a
single library against the target sysroot, but not for a colcon workspace of
interdependent ROS packages. Rather than replace it, both the containerised
and the host SDK paths wrap it: include the SDK's own file, then correct
what stops a ROS workspace from configuring and building for the target.

The wrapper refers to the environment ($ENV{...}) rather than baking in paths
where it can, so the same text works inside a container and on the host, and a
mixin that points at it keeps working for anyone who has sourced the SDK.
"""

WRAPPER_NAME = 'buildx-toolchain.cmake'

# CMake's ${...} syntax collides with str.format, hence %-formatting.
_TEMPLATE = '''\
# Generated by colcon-buildx. Wraps the SDK's own toolchain file.
include("%(toolchain)s")

# 1. The stock OE toolchain builds its sysroot path from
#    ${CMAKE_CURRENT_LIST_DIR}/../../../../.. and never normalizes it. CMake
#    compares prefixes with find roots textually, so a prefix that *is* inside
#    the sysroot but is spelled canonically is not recognised as already rooted:
#    it is re-rooted into a path that does not exist and silently dropped.
set(_buildx_roots "")
foreach(_buildx_root IN LISTS CMAKE_FIND_ROOT_PATH)
  get_filename_component(_buildx_root "${_buildx_root}" REALPATH)
  list(APPEND _buildx_roots "${_buildx_root}")
endforeach()

# 2. CMAKE_FIND_ROOT_PATH_MODE_PACKAGE is ONLY, so find_package() only looks
#    under the find roots. Without the workspace's install prefix among them, a
#    package cannot find the packages built before it in the same workspace.
set(CMAKE_FIND_ROOT_PATH ${_buildx_roots} "%(install_dir)s")

# 3. ros-sdk-env exports AMENT_PREFIX_PATH but not CMAKE_PREFIX_PATH, and sets
#    AMENT_SKIP_SHELL_PATH, which turns off the PATH-based prefix discovery that
#    finds /opt/ros/<distro> on a native install. Without this, the first
#    find_package(ament_cmake) of any ROS package fails.
if(DEFINED ENV{AMENT_PREFIX_PATH})
  string(REPLACE ":" ";" _buildx_ament "$ENV{AMENT_PREFIX_PATH}")
  list(APPEND CMAKE_PREFIX_PATH ${_buildx_ament})
endif()

# 4. Programs run on the build host. An SDK whose sysroot carries the target's
#    own cmake, make or ninja (the OEROS Lyrical SDKs do) otherwise hands CMake
#    an aarch64 ninja, which the host cannot execute.
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)

# 5. FindPython takes Python's include directory from the interpreter it runs,
#    the SDK's own, whose sysroot has no headers. Python.h is in the target's.
if(NOT DEFINED Python3_INCLUDE_DIR)
  set(_buildx_sysroot "${CMAKE_SYSROOT}")
  if(NOT _buildx_sysroot AND DEFINED ENV{OECORE_TARGET_SYSROOT})
    set(_buildx_sysroot "$ENV{OECORE_TARGET_SYSROOT}")
  endif()
  file(GLOB _buildx_python_include LIST_DIRECTORIES true "${_buildx_sysroot}/usr/include/python3.*")
  list(LENGTH _buildx_python_include _buildx_n)
  if(_buildx_n EQUAL 1 AND EXISTS "${_buildx_python_include}/Python.h")
    set(Python3_INCLUDE_DIR "${_buildx_python_include}" CACHE PATH "Target Python headers")
  endif()
endif()

# 6. Compiled Python modules are named for the target's Python, not the SDK's:
#    an x86_64 SDK would tag them cpython-3XX-x86_64-linux-gnu. ros-sdk-env, or
#    colcon-buildx's stand-in for it, exports the target's tag; meta-ros image
#    builds pass the same value as -DPYTHON_SOABI. pybind11 reads the suffix
#    from PYTHON_MODULE_EXTENSION.
if(NOT "$ENV{PYTHON_SOABI}" STREQUAL "")
  set(PYTHON_SOABI "$ENV{PYTHON_SOABI}" CACHE STRING "Target Python ABI tag")
  if(NOT DEFINED PYTHON_MODULE_EXTENSION)
    set(PYTHON_MODULE_EXTENSION ".$ENV{PYTHON_SOABI}.so" CACHE STRING "Target extension suffix")
    set(PYTHON_MODULE_DEBUG_POSTFIX "" CACHE STRING "")
  endif()
endif()
'''


ENV_TOOLCHAIN = '$ENV{OE_CMAKE_TOOLCHAIN_FILE}'


def wrapper_text(install_dir, toolchain=ENV_TOOLCHAIN):
    """
    Return the wrapper toolchain file contents.

    Args:
        install_dir: The colcon install prefix, as seen by the build
        toolchain: The SDK toolchain to wrap; by default whatever ros-sdk-env
            exported, resolved when CMake runs

    Returns:
        str: CMake toolchain file contents
    """
    return _TEMPLATE % {'toolchain': toolchain, 'install_dir': install_dir}


def write_wrapper(path, install_dir, toolchain=ENV_TOOLCHAIN):
    """
    Write the wrapper to *path*, leaving an identical file untouched.

    CMake records an included toolchain file as a configure dependency, so a
    fresh mtime re-configures every package in the workspace -- rerunning the
    rosidl generators in interface packages -- even when nothing changed.
    Rewriting it unconditionally made every incremental build a full
    re-configure.

    Returns:
        Path: *path*
    """
    from pathlib import Path

    path = Path(path)
    text = wrapper_text(install_dir, toolchain)
    if not path.is_file() or path.read_text() != text:
        path.write_text(text)
    return path
